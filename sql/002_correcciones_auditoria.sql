-- Migración opcional para conservar solicitudes después de eliminar un reporte.
-- Ejecutar en AWS RDS / pgAdmin conectado a la base existente.
-- Compatible con el esquema italia ya creado.
BEGIN;

-- Eliminar primero la FK con ON DELETE CASCADE actual.
ALTER TABLE italia.correcciones
    DROP CONSTRAINT IF EXISTS correcciones_id_asociado_fkey;

-- Permitir conservar el ID histórico de un reporte eliminado.
-- id_asociado sigue siendo obligatorio y almacena el ID original,
-- pero deja de depender de una fila presente en italia.reportes.

-- Bitácora de aplicaciones de solicitudes
CREATE TABLE IF NOT EXISTS italia.correcciones_auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correccion_id BIGINT NOT NULL,
    reporte_id BIGINT NOT NULL,
    cedula_solicitante VARCHAR(30) NOT NULL,
    accion VARCHAR(20) NOT NULL CHECK (accion IN ('Modificar','Eliminar')),
    columna VARCHAR(100),
    valor_anterior TEXT,
    valor_nuevo TEXT,
    procesado_por VARCHAR(30) NOT NULL,
    procesado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
ALTER TABLE italia.correcciones_auditoria OWNER TO rw_reportesperu;
CREATE INDEX IF NOT EXISTS idx_italia_auditoria_reporte
    ON italia.correcciones_auditoria(reporte_id);
COMMIT;
